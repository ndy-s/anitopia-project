export const PIXEL_GLYPH_WIDTH = 5;
export const PIXEL_GLYPH_HEIGHT = 7;
export const PIXEL_GLYPH_ADVANCE = 6; // 5 wide + 1 space column

export function measurePixelText(text: string, pixelSize: number): number {
    return text.length * PIXEL_GLYPH_ADVANCE * pixelSize - pixelSize;
}

/**
 * Draws blocky bitmap text at (x, y) — top-left origin, not baseline. Always uppercased.
 * Returns the rendered width in canvas pixels (useful for manual centering/layout).
 */
export function drawPixelText(ctx: SKRSContext2D, text: string, x: number, y: number, pixelSize: number, color: string): number {
    ctx.fillStyle = color;
    let cursorX = x;
    for (const char of text.toUpperCase()) {
        const glyph = FONT_5X7[char] ?? FONT_5X7[' '];
        for (let row = 0; row < PIXEL_GLYPH_HEIGHT; row++) {
            for (let col = 0; col < PIXEL_GLYPH_WIDTH; col++) {
                if (glyph[row][col] === '#') {
                    ctx.fillRect(cursorX + col * pixelSize, y + row * pixelSize, pixelSize, pixelSize);
                }
            }
        }
        cursorX += PIXEL_GLYPH_ADVANCE * pixelSize;
    }
    return cursorX - x - pixelSize;
}

export function drawPixelTextCentered(ctx: SKRSContext2D, text: string, centerX: number, y: number, pixelSize: number, color: string): number {
    const width = measurePixelText(text, pixelSize);
    return drawPixelText(ctx, text, centerX - width / 2, y, pixelSize, color);
}
